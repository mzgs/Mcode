static cui_ctx *g_active_theme_ui = NULL;
static app_theme_mode g_active_resolved_theme = APP_THEME_DARK;

const app_theme_spec *app_theme_spec_get(app_theme_mode mode) {
    if (mode < 0 || mode >= APP_THEME_COUNT) return &k_theme_specs[APP_THEME_DARK];
    return &k_theme_specs[mode];
}

const app_theme_mode *app_theme_display_order(int *out_count) {
    if (out_count) *out_count = APP_THEME_COUNT;
    return k_display_order;
}

void app_theme_apply(cui_ctx *ui, app_theme_mode resolved_mode, cui_accent accent) {
    if (!ui) return;
    if (resolved_mode <= APP_THEME_SYSTEM || resolved_mode >= APP_THEME_COUNT) {
        resolved_mode = (cui_get_theme_mode(ui) == CUI_THEME_DARK)
            ? APP_THEME_DARK : APP_THEME_LIGHT;
    }

    const app_theme_spec *s = &k_theme_specs[resolved_mode];
    g_active_theme_ui = ui;
    g_active_resolved_theme = resolved_mode;

    cui_theme *t = cui_theme_get(ui);
    cui_color *c = t->colors;

    c[CUI_TOKEN_BACKGROUND]          = s->background;
    c[CUI_TOKEN_SURFACE]             = s->surface;
    c[CUI_TOKEN_SURFACE_RAISED]      = s->surface_raised;
    c[CUI_TOKEN_SURFACE_MUTED]       = s->surface_muted;
    c[CUI_TOKEN_FOREGROUND]          = s->foreground;
    c[CUI_TOKEN_TEXT_SECONDARY]      = s->text_secondary;
    c[CUI_TOKEN_TEXT_MUTED]          = s->text_muted;
    c[CUI_TOKEN_BORDER]              = s->border;
    c[CUI_TOKEN_BORDER_SUBTLE]       = s->border_subtle;
    c[CUI_TOKEN_BORDER_STRONG]       = s->border_strong;
    c[CUI_TOKEN_CONTROL_TRACK]       = s->control_track;
    c[CUI_TOKEN_CONTROL_TRACK_HOVER] = s->control_track_hover;
    c[CUI_TOKEN_CONTROL_THUMB]       = s->control_thumb;

    c[CUI_TOKEN_SUCCESS] = s->success;
    c[CUI_TOKEN_WARNING] = s->warning;
    c[CUI_TOKEN_DANGER]  = s->danger;
    c[CUI_TOKEN_INFO]    = s->info;

    t->tone_sky    = s->tone_sky;
    t->tone_teal   = s->tone_teal;
    t->tone_green  = s->tone_green;
    t->tone_amber  = s->tone_amber;
    t->tone_rose   = s->tone_rose;
    t->tone_orchid = s->tone_orchid;
    t->tone_violet = s->tone_violet;

    c[CUI_TOKEN_HOVER]  = cui_alpha(s->foreground, s->is_dark ? 0.055f : 0.05f);
    c[CUI_TOKEN_ACTIVE] = cui_alpha(s->foreground, s->is_dark ? 0.085f : 0.075f);
    c[CUI_TOKEN_SCRIM]  = s->scrim;

    if (accent == CUI_ACCENT_NEUTRAL) {
        c[CUI_TOKEN_ACCENT]            = s->accent;
        c[CUI_TOKEN_ACCENT_STRONG]     = s->accent_strong;
        c[CUI_TOKEN_ACCENT_SUBTLE]     = s->accent_subtle;
        c[CUI_TOKEN_ACCENT_FOREGROUND] = s->accent_foreground;
        c[CUI_TOKEN_CONTROL_ON]        = s->control_on;
        c[CUI_TOKEN_CONTROL_GLYPH]     = s->control_glyph;
        c[CUI_TOKEN_CONTROL_THUMB_ON]  = s->control_thumb_on;
        c[CUI_TOKEN_FOCUS_RING]        = s->focus_ring;
        for (int i = 0; i < 6; ++i) {
            c[CUI_TOKEN_SERIES_1 + i] = s->series[i];
        }
    }
}

const app_theme_spec *app_theme_current(cui_ctx *ui) {
    if (ui && ui == g_active_theme_ui &&
        g_active_resolved_theme > APP_THEME_SYSTEM &&
        g_active_resolved_theme < APP_THEME_COUNT) {
        return &k_theme_specs[g_active_resolved_theme];
    }
    bool dark = ui ? (cui_get_theme_mode(ui) == CUI_THEME_DARK) : true;
    return &k_theme_specs[dark ? APP_THEME_DARK : APP_THEME_LIGHT];
}

bool app_theme_has_accent(cui_ctx *ui) {
    if (!ui) return false;
    if (cui_get_accent(ui) != CUI_ACCENT_NEUTRAL) return true;
    const app_theme_spec *spec = app_theme_current(ui);
    return spec && spec->has_accent;
}
